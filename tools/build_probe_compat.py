"""Generate RadioProbe/Compat.lua: every name the addon might need from the client.

Dev-only. It scans the addon's Lua files for capitalized identifiers, C_* namespaces,
widget methods (":Method("), templates, frame types and event-like strings. The list
is deliberately generous: addon-local names show up as "missing" on every client, so
compare two clients with tools/probe_diff.py instead of reading one result alone.

Usage: python tools/build_probe_compat.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ADDON = ROOT / "KalimdorZugZugRadio"
OUT = ROOT / "RadioProbe" / "Compat.lua"
SKIP = {"Locales.lua", "GameMusic.lua", "Library.lua"}

# Widgets the probe creates to test methods; the addon uses these types.
FRAME_TYPES = ["Frame", "Button", "CheckButton", "EditBox", "Slider", "StatusBar",
               "ScrollFrame", "DropdownButton", "GameTooltip"]
TEMPLATE_TYPES = {
    "BackdropTemplate": "Frame",
    "GameTooltipTemplate": "GameTooltip",
    "InputBoxTemplate": "EditBox",
    "UIPanelButtonTemplate": "Button",
    "UIPanelScrollFrameTemplate": "ScrollFrame",
    "WowStyle1DropdownTemplate": "DropdownButton",
}


def lua_list(name, items):
    body = ",\n".join(f'    "{i}"' for i in sorted(items))
    return f"  {name} = {{\n{body},\n  }},\n"


def main():
    raw = "\n".join(p.read_text(encoding="utf-8") for p in sorted(ADDON.glob("*.lua")) if p.name not in SKIP)
    raw += "\n" + (ADDON / "Bindings.xml").read_text(encoding="utf-8")
    code = re.sub(r"--[^\n]*", "", raw)
    strings = re.findall(r'"((?:\\.|[^"\\])*)"', code)
    code_no_str = re.sub(r'"(?:\\.|[^"\\])*"', '""', code)

    globals_ = set(re.findall(r"(?<![\w.:])([A-Z][A-Za-z0-9_]+)\b", code_no_str))
    globals_ |= set(re.findall(r"(?<![\w.:])((?:C_\w+|Settings|SettingsPanel|MenuUtil|Menu|"
                               r"AddonCompartmentFrame|Minimap|GameTooltip|ChatFrame1)\.\w+)", code_no_str))
    globals_ |= {"issecretvalue", "canaccessvalue", "hooksecurefunc", "debugprofilestop", "date", "time"}
    methods = set(re.findall(r":([A-Z]\w+)\s*\(", code_no_str))
    events = {s for s in strings if re.fullmatch(r"[A-Z][A-Z0-9]+(?:_[A-Z0-9]+)+", s)}
    templates = set(TEMPLATE_TYPES) | {s for s in strings if s.endswith("Template")}

    OUT.write_text(
        "-- GENERATED by tools/build_probe_compat.py from the addon's code: don't hand-edit.\n"
        "RadioProbeCompat = {\n"
        + lua_list("globals", globals_)
        + lua_list("methods", methods)
        + lua_list("events", events)
        + lua_list("frameTypes", FRAME_TYPES)
        + "  templates = {\n"
        + "".join(f'    {{ "{t}", "{TEMPLATE_TYPES.get(t, "Frame")}" }},\n' for t in sorted(templates))
        + "  },\n}\n",
        encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {len(globals_)} globals, {len(methods)} methods, "
          f"{len(events)} events, {len(templates)} templates")


if __name__ == "__main__":
    main()
