---------------------------------------------------------------------------
-- Scelta della lingua
---------------------------------------------------------------------------
local function clientLocale()
  local loc = GetLocale and GetLocale() or "enUS"
  if loc == "enGB" then loc = "enUS" end
  return loc
end

local function lookup(lang, key)
  local t = LOCALES[lang]
  local v = t and t[key]
  if v == nil then v = LOCALES.enUS[key] end
  return v == nil and key or v
end

ns.lang, ns.chatLang = "enUS", "enUS"
ns.L = setmetatable({}, { __index = function(_, key) return lookup(ns.lang, key) end })
ns.CL = setmetatable({}, { __index = function(_, key) return lookup(ns.chatLang, key) end })

-- pref: codice lingua salvato oppure nil/"auto" = lingua del client.
function ns.InitLanguage(pref)
  local client = clientLocale()
  local lang = (pref and LOCALES[pref]) and pref or (LOCALES[client] and client or "enUS")
  ns.lang = lang
  -- Font dell'addon solo per una lingua CJK che il client non ha.
  -- Su un client zh/ko si usano i font del gioco (eccetto il giapponese, che WoW non ha).
  ns.useAddonFont = CJK[lang] and (lang == "jaJP" or not CJK[client]) or false
  ns.clientHasCJK = CJK[client] or false
  ns.chatLang = ns.useAddonFont and "enUS" or lang
end

-- Testi dell'utente (titoli, artisti, cartelle, nomi playlist) possono contenere caratteri
-- giapponesi/cinesi/coreani anche con un'interfaccia in inglese: lead byte UTF-8 E3-ED.
local CJK_PATTERN = "[\227-\237][\128-\191][\128-\191]"
function ns.HasCJK(text)
  return type(text) == "string" and not ns.clientHasCJK and text:find(CJK_PATTERN) ~= nil
end

-- SetText che sceglie il font: quello dell'addon se il testo contiene caratteri CJK.
-- Nota: SetFontObject reimposta il colore, quindi va riapplicato dopo.
function ns.SetText(fs, text, template)
  local want = ns.FontObject(template, ns.HasCJK(text))
  if want and fs.kzzFont ~= want then
    fs:SetFontObject(want)
    fs.kzzFont = want
  end
  fs:SetText(text)
end

---------------------------------------------------------------------------
-- Font: copie dei font object di Blizzard con il font dell'addon.
---------------------------------------------------------------------------
local fontCache = {}

-- Restituisce il nome di un font object da usare al posto di `template`.
function ns.Font(template, force)
  if not (ns.useAddonFont or force) or not _G[template] or not CreateFont then return template end
  local name = "KZZR_" .. template
  if fontCache[name] == nil then
    local base = _G[template]
    local obj = CreateFont(name)
    obj:CopyFontObject(base)
    local _, size, flags = base:GetFont()
    local ok, res = pcall(obj.SetFont, obj, ns.CJK_FONT_PATH, size or 12, flags or "")
    fontCache[name] = ok and res ~= false
  end
  return fontCache[name] and name or template
end

function ns.FontObject(template, force)
  return _G[ns.Font(template, force)]
end

-- Applica il font dell'addon a una voce dei menu Blizzard (Menu API).
function ns.StyleMenuItem(description, force)
  if not (ns.useAddonFont or force) or not description or not description.AddInitializer then return end
  local fo = ns.FontObject("GameFontHighlightSmall", force)
  pcall(description.AddInitializer, description, function(button)
    local fs = button.fontString or button.Text
    if fs and fo then fs:SetFontObject(fo) end
  end)
end
